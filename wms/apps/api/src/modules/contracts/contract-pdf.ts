      section: { fontSize: 10.5, bold: true, alignment: 'center', margin: [0, 12, 0, 6] },
      paragraph: { margin: [0, 0, 0, 3] },
      requisitesTitle: { bold: true, fontSize: 9.5, margin: [0, 0, 0, 6] },
      requisites: { bold: true, fontSize: 8.2, lineHeight: 1.08, alignment: 'left' },
