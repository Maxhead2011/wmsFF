function sectionContent(section: ContractSection): Content[] {
  return [
    { text: section.title, style: 'section' },
    ...section.paragraphs.map((text) => ({ text, style: 'paragraph' }) as Content),
  ];
}

function requisitesBlock(input: ContractPdfInput): Content {
  return {
    columns: [
      {
        width: '48%',
        stack: [
          { text: 'Заказчик:', style: 'requisitesTitle' },
          { text: clientRequisites(input.client), style: 'requisites' },
          {
            stack: [
              { text: 'Доступ в WMS:', style: 'accessLabel', margin: [0, 12, 0, 3] },
              { text: `Адрес: ${input.wmsUrl}`, style: 'requisites' },
              { text: `Логин: ${input.wmsLogin}`, style: 'requisites' },
              { text: `Пароль: ${input.wmsPassword}`, style: 'requisites' },
            ],
          },
          { text: '\n\n__________________________', margin: [0, 20, 0, 0], alignment: 'left' },
          { text: 'подпись / М.П.', style: 'signatureCaption', alignment: 'left' },
        ],
      },
      {
        width: '48%',
        stack: [
          { text: 'Исполнитель:', style: 'requisitesTitle' },
          { text: executorRequisites(input.executor), style: 'requisites' },
          executorSignature(input.executor),
        ],
      },
    ],
    columnGap: 22,
  };
}

function executorSignature(executor: ContractPartySnapshot): Content {
  const stamp =
    executor.stampDataUrl ||
    (executor.inn === '616602423102' ? billingAssetDataUrl('stamp') : null);
  const signature =
    executor.signatureDataUrl ||
    (executor.inn === '616602423102' ? billingAssetDataUrl('signature') : null);
  const stack: Content[] = [{ text: '', margin: [0, 14, 0, 0] }];
  if (stamp) {
    stack.push({ image: stamp, width: 116, opacity: 0.84, margin: [58, 0, 0, -91] });
  }
  if (signature) {
    stack.push({ image: signature, width: 126, opacity: 0.92, margin: [16, 2, 0, -7] });
  }
  stack.push(
    { canvas: [{ type: 'line', x1: 0, y1: 0, x2: 205, y2: 0, lineWidth: 0.6 }] },
    { text: `${executor.name} / подпись / М.П.`, style: 'signatureCaption' },
  );
  return { stack };
}

function clientRequisites(client: ContractPartySnapshot) {
  return [
    client.fullName || client.name,
    client.inn ? `ИНН: ${client.inn}` : 'ИНН: —',
    client.kpp ? `КПП: ${client.kpp}` : '',
    client.ogrn ? `${client.kind === 'INDIVIDUAL_ENTREPRENEUR' ? 'ОГРНИП' : 'ОГРН'}: ${client.ogrn}` : '',
    client.legalAddress ? `Юр. адрес: ${client.legalAddress}` : '',
    client.actualAddress ? `Факт. адрес: ${client.actualAddress}` : '',
    client.bankName ? `Банк: ${client.bankName}` : '',
    client.bankAccount ? `Расчётный счёт: ${client.bankAccount}` : '',
    client.correspondentAccount ? `Корсчёт: ${client.correspondentAccount}` : '',
    client.bankBik ? `БИК: ${client.bankBik}` : '',
    client.phone ? `Телефон: ${client.phone}` : '',
    client.email ? `E-mail: ${client.email}` : '',
  ]
    .filter(Boolean)
    .join('\n');
}

