  legalAddress?: string | null;
  actualAddress?: string | null;
  phone?: string | null;
  email?: string | null;
  bankName?: string | null;
  bankBik?: string | null;
  bankAccount?: string | null;
  correspondentAccount?: string | null;
  stampDataUrl?: string | null;
  signatureDataUrl?: string | null;
