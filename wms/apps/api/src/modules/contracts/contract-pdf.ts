function executorLead(executor: ContractPartySnapshot) {
  return executor.fullName || 'Индивидуальный предприниматель Говорова Екатерина Ивановна';
}

function clientLead(client: ContractPartySnapshot) {
  const fullName = client.fullName || client.name;
  const normalized = fullName.trim().toLocaleLowerCase('ru-RU');
  if (normalized.startsWith('индивидуальный предприниматель ') || normalized.startsWith('ип ')) {
    return fullName;
  }
  if (client.kind === 'INDIVIDUAL_ENTREPRENEUR') {
    return `Индивидуальный предприниматель ${fullName}`;
  }
  return fullName;
}

function formatContractDate(value: Date) {
  const day = String(value.getUTCDate()).padStart(2, '0');
  const month = new Intl.DateTimeFormat('ru-RU', { month: 'long', timeZone: 'UTC' }).format(value);
  const year = value.getUTCFullYear();
  return `«${day}» ${month} ${year} г.`;
}

