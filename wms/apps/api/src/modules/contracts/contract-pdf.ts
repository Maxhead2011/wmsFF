export type ContractPdfInput = {
  number: string;
  contractDate: Date;
  client: ContractPartySnapshot;
  executor: ContractPartySnapshot;
  wmsUrl: string;
  wmsLogin: string;
  wmsPassword: string;
};

type ContractSection = {
  title: string;
  paragraphs: string[];
};

export async function renderContractPdf(input: ContractPdfInput) {
  configurePdfMake();
  return pdfMake.createPdf(contractDefinition(input)).getBuffer();
}

