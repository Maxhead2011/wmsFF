 const customer={...admin,id:'customer',roleCodes:['CLIENT'],permissionCodes:[],clientScopeMode:'LIMITED',clientIds:[a.id],writableClientIds:[a.id],activeWarehouseId:'stale'};
 const first=await service.list('',admin,undefined,'active','true');
 const second=await service.list('',admin,undefined,'active','true',String(first.at(-1).number));
 const third=await service.list('',admin,undefined,'active','true',String(second.at(-1).number));
 assert.deepEqual([first.length,second.length,third.length],[100,100,6]);
 const all=[...first,...second,...third];
 assert.equal(new Set(all.map(r=>r.number)).size,206);
 assert.deepEqual(all.map(r=>r.number),[...all.map(r=>r.number)].sort((x,y)=>y-x));
 assert(!all.some(r=>[otherBranch.id,hiddenRequest.id,nonOzon.id,...closed.map(c=>c.id)].includes(r.id)));passed++;
 // Disconnected clients remain discoverable in existing assemblies, without active connection lookups.
 const saved=all.find(r=>r.id===otherClient.id);
 assert(saved);assert.equal(saved.clientId,b.id);assert.equal(saved.clientName,'Client B');assert.equal(saved.clientCode,'B');assert.equal(saved.warehouseName,w.name);
 assert.equal(saved.itemCount,4);assert.equal(saved.quantity,10);assert.equal(saved.itemsPreview.length,3);assert(saved.createdAt);passed++;
 const single=await service.list(b.id,admin,undefined,'active','true');
 assert.deepEqual(single.map(r=>r.id),[otherClient.id]);passed++;
 const own=await service.list('',customer,undefined,'active','true');
 assert(own.every(r=>r.clientId===a.id));assert(own.some(r=>r.id===otherBranch.id));
 assert(!own.some(r=>r.id===otherClient.id));
 await assert.rejects(service.list(b.id,customer,undefined,'active','true'));
 assert.deepEqual(await service.list('',{...customer,clientIds:[]},undefined,'active','true'),[]);passed++;
 const branch={...customer,roleCodes:['BRANCH_MANAGER'],clientScopeMode:'ALL',activeWarehouseId:w2.id,warehouseIds:[w2.id],writableWarehouseIds:[]};
 assert.deepEqual((await service.list('',branch,undefined,'active','true')).map(r=>r.id),[otherBranch.id]);
