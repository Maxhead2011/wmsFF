 await p.warehouseClient.createMany({data:[{clientId:a.id,warehouseId:w.id},{clientId:a.id,warehouseId:w2.id},{clientId:b.id,warehouseId:w.id,status:'INACTIVE'}]});
 const base={clientId:a.id,warehouseId:w.id,type:'OUTBOUND',title:'Ozon'};
 let sequence=0;
 const shipment=()=>({create:{importKey:'test-'+(++sequence),directions:[{name:'Moscow',items:[]}]}});
 const main=[];
 for(let n=0;n<205;n++) main.push(await p.clientRequest.create({data:{...base,ozonShipment:shipment()}}));
