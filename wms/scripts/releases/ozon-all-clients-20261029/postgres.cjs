 await assert.rejects(service.list('',{...branch,activeWarehouseId:null},undefined,'active','true'));
 await assert.rejects(service.list('',admin,w2.id,'active','true'));passed++;
 assert.deepEqual((await service.list('',admin,undefined,'completed','true')).map(r=>r.id),[...closed].reverse().map(r=>r.id));
 assert.deepEqual((await service.list('',{...admin,activeWarehouseId:w2.id},undefined,'active','true')).map(r=>r.id),[otherBranch.id]);passed++;
